export const nicknameLimit=6;
export const nicknameHint='닉네임은 최대 '+nicknameLimit+'자까지 입력할 수 있어.';

const segmenter=typeof Intl.Segmenter==='function'?new Intl.Segmenter('ko',{granularity:'grapheme'}):null;
// Older browsers lack Segmenter. Keep combined accents, flags and joined emoji together.
const fallbackCluster=/\p{Regional_Indicator}{2}|\P{Mark}[\p{Mark}\p{Emoji_Modifier}\u{e0020}-\u{e007f}]*(?:\u200d.[\p{Mark}\p{Emoji_Modifier}\u{e0020}-\u{e007f}]*)*|./gsu;

export function limitNickname(value){
  const text=value.normalize('NFC');
  const clusters=segmenter?segmenter.segment(text):text.matchAll(fallbackCluster);
  let result='',count=0;
  for(const cluster of clusters){
    if(count++===nicknameLimit)break;
    result+=segmenter?cluster.segment:cluster[0];
  }
  return result;
}

export function validNickname(text){
  return typeof text==='string'&&!/[\x00-\x1f\x7f]/.test(text)&&text===limitNickname(text);
}

const adjectives=['초록','복슬','졸린','느긋','씩씩','포근'];
const animals=['냥이','치즈','주주','범이','토끼','햄찌'];
export function defaultNickname(){
  const pick=words=>words[Math.floor(Math.random()*words.length)];
  return pick(adjectives)+pick(animals)+String(Math.floor(Math.random()*90)+10);
}

export function displayNickname(value,memberNumber){
  const text=String(value??'').trim().normalize('NFC');
  if(!text){
    if(!memberNumber)return '';
    const number=String(memberNumber);
    if(number.length<=2)return '게스트 '+number;
    return limitNickname((number.length===3?'게스트':'냥')+number);
  }
  const short=limitNickname(text);
  if(short===text)return text;
  // Keep the distinguishing digits in names generated by older game versions.
  const old=/^(초록|복슬|졸린|느긋한|씩씩한|포근한)(고양이|치즈냥|주주|호랑이|토끼|햄스터)(\d{2})$/.exec(text);
  if(!old)return short;
  const animal={'고양이':'냥이','치즈냥':'치즈','호랑이':'범이','햄스터':'햄찌'}[old[2]]??old[2];
  return old[1].slice(0,2)+animal+old[3];
}
