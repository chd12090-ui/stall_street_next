const profiles=new Map();
export function companyProfile(input){
  const asset=equityAsset(input);
  if(!asset||asset.kind!=='주식')return null;
  if(profiles.has(asset.code))return profiles.get(asset.code);
  const business=descriptions.get(asset.code);
  if(!business)return null;
  const country=countries[asset.country]?.name??asset.country;
  const partners=asset.exposure.map(id=>countries[id]?.name).filter(Boolean);
  const riskFactors=Object.freeze([...new Set([...business.riskFactors,...(partners.length?['환율']:[])])]);
  const [product,customers]=issuerBusiness[asset.code]??[business.product,business.customers];
  const profile=Object.freeze({...business,product,customers,groupLabel:business.group,
    sector:asset.sector,industryIds:asset.industryIds,country,currency:asset.currency,
    financial:business.group==='은행·여신',riskFactors,markets:[country,...partners].join(' · '),
    exposures:riskFactors.join(' · '),assumptions:'게임 속 사업 가정이야. 게임 4일을 회계 한 분기로 압축하고 마감 6시간 뒤에 공시해. 별도 재무제표 기준이며 보통주 한 종류만 발행해. 현금은 전액 사용 가능하고 리스·우선주·비지배지분은 없어.'});
  profiles.set(asset.code,profile);
  return profile;
}
