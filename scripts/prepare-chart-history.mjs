// Rebuild the static price archive after changing the historical tape algorithm or fund catalog.
import {mkdir,readdir,rm,writeFile} from 'node:fs/promises';
import {stocks,markets,runsOn} from '../src/game/world.mjs';
import {sessionBars,combine,listingDay} from '../src/game/tape.mjs';
import {historySignature,packHistory} from '../src/game/chart-archive-codec.mjs';
const directory=new URL('../src/game/fund-history/',import.meta.url);
await mkdir(directory,{recursive:true});
const banner='// Generated by scripts/prepare-chart-history.mjs.\n';
const loaders=new Map();
for(const [i,s] of stocks.entries()){
  if(!s.reference)continue;
  const rows=[];
  for(let day=listingDay(i);day<0;day++)if(runsOn(s.market,day))rows.push(combine(sessionBars(day,i)));
  const history=[historySignature(s,stocks,markets),packHistory(rows)];
  const file=s.code+'.mjs';
  await writeFile(new URL(file,directory),banner+'export default '+JSON.stringify(history)+';\n');
  loaders.set(file,'  '+s.code+':()=>import(\'./'+file+'\'),');
}
await writeFile(new URL('index.mjs',directory),banner+'export const fundHistoryLoaders={\n'+[...loaders.values()].join('\n')+'\n};\n');
for(const file of await readdir(directory)){
  if(/^[A-Z0-9]+\.mjs$/.test(file)&&!loaders.has(file))await rm(new URL(file,directory));
}
