// Bundles db/migrations/*.sql into src/server/db/migrations.generated.mjs so the
// browser database (and any server adapter) can apply them without file access.
// Runs automatically before `npm run dev`, `npm run build` and `npm test`.
//   node scripts/build-migrations.mjs          write the generated module
//   node scripts/build-migrations.mjs --check  fail if it is out of date
import {readFile, writeFile} from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const folder = new URL('db/migrations/', root);
const target = new URL('src/server/db/migrations.generated.mjs', root);

const journal = JSON.parse(await readFile(new URL('meta/_journal.json', folder), 'utf8'));
const entries = [...journal.entries].sort((a, b) => a.idx - b.idx);
const migrations = [];
for (const {tag} of entries) migrations.push({name: tag, sql: await readFile(new URL(tag + '.sql', folder), 'utf8')});

const source = '// Generated by scripts/build-migrations.mjs from db/migrations. Do not edit by hand.\n'
  + 'export const migrations = Object.freeze(' + JSON.stringify(migrations, null, 2) + ');\n';

if (process.argv.includes('--check')) {
  const current = await readFile(target, 'utf8').catch(() => '');
  if (current !== source) {
    console.error('src/server/db/migrations.generated.mjs is out of date. Run: node scripts/build-migrations.mjs');
    process.exit(1);
  }
} else {
  const current = await readFile(target, 'utf8').catch(() => '');
  if (current !== source) await writeFile(target, source);
  console.log('migrations: ' + migrations.length + ' bundled');
}
